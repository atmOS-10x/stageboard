import fs from "node:fs"
import path from "node:path"
import fg from "fast-glob"
import { variantKeyFromFile, type VariantFile } from "../core/protocol"
import type { ResolvedConfig } from "./config"

const DEFAULT_GLOBS = ["**/*.variant.{tsx,jsx,ts,js}"]
const IGNORE = ["**/node_modules/**", "**/.next/**", "**/dist/**", "**/.stageboard/**"]

function str(source: string, key: string): string | undefined {
  const m = new RegExp(`\\b${key}\\s*:\\s*(["'\`])((?:\\\\.|(?!\\1).)*)\\1`).exec(source)
  return m?.[2]
}

export function readVariantFile(config: ResolvedConfig, absFile: string): VariantFile | undefined {
  let source: string
  try {
    source = fs.readFileSync(absFile, "utf8")
  } catch {
    return undefined
  }
  const block = /export\s+const\s+variant\b[\s\S]*?\}/.exec(source)?.[0]
  if (!block) return undefined
  const of = str(block, "of")
  if (!of) return undefined
  const file = path.relative(config.root, absFile).split(path.sep).join("/")
  const key = variantKeyFromFile(file)
  return {
    key,
    of,
    label: str(block, "label") ?? key,
    description: str(block, "description"),
    job: str(block, "job"),
    file,
  }
}

export async function scanVariants(config: ResolvedConfig): Promise<VariantFile[]> {
  const files = await fg(config.variantGlobs ?? DEFAULT_GLOBS, {
    cwd: config.root,
    absolute: true,
    ignore: [...IGNORE, ...(config.ignore ?? [])],
  })
  return files
    .map((f) => readVariantFile(config, f))
    .filter((v): v is VariantFile => Boolean(v))
    .sort((a, b) => a.file.localeCompare(b.file))
}

export function renderVariantsModule(config: ResolvedConfig, variants: VariantFile[]): string {
  const dir = path.dirname(config.variantsFile)
  const lines = [
    "// Generated by stageboard. Do not edit; it is rewritten whenever *.variant.tsx files change.",
    'import { registerVariants } from "@atmos.build/stageboard/react"',
  ]
  variants.forEach((v, i) => {
    let rel = path.relative(dir, path.join(config.root, v.file)).split(path.sep).join("/")
    rel = rel.replace(/\.(tsx|ts|jsx|js)$/, "")
    if (!rel.startsWith(".")) rel = `./${rel}`
    lines.push(`import * as v${i} from ${JSON.stringify(rel)}`)
  })
  lines.push("")
  lines.push("registerVariants([")
  variants.forEach((v, i) => lines.push(`  { file: ${JSON.stringify(v.file)}, module: v${i} },`))
  lines.push("])")
  lines.push("")
  return lines.join("\n")
}

export async function writeVariantsModule(config: ResolvedConfig, variants?: VariantFile[]): Promise<{ changed: boolean; variants: VariantFile[] }> {
  const list = variants ?? (await scanVariants(config))
  const next = renderVariantsModule(config, list)
  const prev = fs.existsSync(config.variantsFile) ? fs.readFileSync(config.variantsFile, "utf8") : ""
  if (prev === next) return { changed: false, variants: list }
  fs.writeFileSync(config.variantsFile, next)
  return { changed: true, variants: list }
}
